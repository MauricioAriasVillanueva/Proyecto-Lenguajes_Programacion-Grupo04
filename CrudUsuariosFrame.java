    private void guardarEnArchivoTxt(String id, String nombre, String correo) {
    // El archivo se guardará dentro de la carpeta raíz de tu proyecto
    String rutaArchivo = "usuarios.txt";

    // 'true' en FileWriter habilita el modo 'append' (anexar sin borrar los anteriores)
    try (FileWriter fw = new FileWriter(rutaArchivo, true);
         BufferedWriter bw = new BufferedWriter(fw)) {

        String registro = id + " | " + nombre + " | " + correo;
        bw.write(registro);
        bw.newLine(); // Salto de línea

        JOptionPane.showMessageDialog(this, 
            "Usuario registrado correctamente en el bloc de notas (usuarios.txt).");

    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, 
            "Error al guardar en el archivo: " + e.getMessage(), 
            "Error IO", 
            JOptionPane.ERROR_MESSAGE);
    }
}
   
