    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
    String id = txtId.getText().trim();
    String nombre = txtNombre.getText().trim();
    String correo = txtCorreo.getText().trim();

    // Validar que los campos no estén vacíos
    if (id.isEmpty() || nombre.isEmpty() || correo.isEmpty()) {
        JOptionPane.showMessageDialog(this, 
            "Por favor, complete todos los campos.", 
            "Campos Incompletos", 
            JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Guardar los datos
    if (service.registrarUsuario(id, nombre, correo)) {
    javax.swing.JOptionPane.showMessageDialog(this, "Usuario registrado correctamente en el bloc de notas (usuarios.txt).");
    txtId.setText("");
    txtNombre.setText("");
    txtCorreo.setText("");
    txtId.requestFocus();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar el usuario.", "Error IO", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

